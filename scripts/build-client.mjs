import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pricingPath = path.join(root, 'src', 'pricing.js');
const templatePath = path.join(root, 'src', 'client-template.js');
const outputPath = path.join(root, 'client.js');
const marker = '    /* __PRICING__ */';

const pricing = fs.readFileSync(pricingPath, 'utf8')
  .replace(/^export /gm, '')
  .trimEnd();
if (/^export /m.test(pricing)) throw new Error('unexported pricing source still contains an export');

const template = fs.readFileSync(templatePath, 'utf8');
if (!template.includes(marker)) throw new Error(`client template is missing ${marker}`);

const indented = pricing.split('\n').map((line) => (line === '' ? '' : `    ${line}`)).join('\n');
const header = '/* Generated by scripts/build-client.mjs. Edit src/client-template.js or src/pricing.js instead. */\n';
fs.writeFileSync(outputPath, header + template.replace(marker, () => indented));
console.log(`built ${path.relative(root, outputPath)}`);
